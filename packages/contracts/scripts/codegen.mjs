#!/usr/bin/env node
/**
 * RevGate SSOT codegen (IMPLEMENTATION_BLUEPRINT §1.1)
 *
 *   schemas/*.schema.json  ──►  ts/*.ts                       (json-schema-to-typescript)
 *                          ──►  py/revgate_contracts/*.py     (datamodel-code-generator, Pydantic v2)
 *
 * Usage
 *   node scripts/codegen.mjs           generate + verify
 *   node scripts/codegen.mjs --check   regenerate in a temp dir, fail on drift vs committed files, verify
 *
 * Verification (both modes)
 *   1. Ajv (draft 2020-12, strict, discriminator) compiles every schema and validates the examples
 *      + must reject a set of known-bad documents.
 *   2. tsc --strict type-checks the generated TS against the examples (via `satisfies`).
 *   3. Pydantic v2 models (uv) validate the examples, reject the bad documents and agree with
 *      jsonschema on every case (scripts/verify_py.py).
 */
import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { cp, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import { compile } from "json-schema-to-typescript";

const require = createRequire(import.meta.url);
const PKG_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA_DIR = path.join(PKG_ROOT, "schemas");
const EXAMPLE_DIR = path.join(PKG_ROOT, "examples");
const PY_PROJECT = path.join(PKG_ROOT, "py");

/** Pinned generator version (reproducible output). */
const DMCG_VERSION = "0.100.0";
const SCHEMA_VERSION = "1.0.0";

const CONTRACTS = [
  { module: "analytical_meta", root: "AnalyticalMeta", schema: "analytical_meta.schema.json" },
  { module: "diff_manifest", root: "DiffManifest", schema: "diff_manifest.schema.json" },
  // Phase 4: approval snapshot + the shared manufacturing $defs (SpecCardV2, SpecDiffItem, MissingSpecWarning,
  // AttachmentItem, ...). Some $defs are not reachable from the root, so emit every definition.
  { module: "manufacturing", root: "ApprovalSnapshot", schema: "manufacturing.schema.json", allDefinitions: true },
];

const TS_BANNER = `/* eslint-disable */
/**
 * GENERATED by packages/contracts/scripts/codegen.mjs from packages/contracts/schemas — DO NOT EDIT.
 * Run \`pnpm codegen\` after changing a schema.
 */`;

const PY_HEADER =
  "# GENERATED by packages/contracts/scripts/codegen.mjs (datamodel-code-generator " +
  DMCG_VERSION +
  ") from packages/contracts/schemas - DO NOT EDIT.";

const checkMode = process.argv.includes("--check");

function log(msg) {
  console.log(`[codegen] ${msg}`);
}

function fail(msg) {
  console.error(`[codegen] ERROR: ${msg}`);
  process.exit(1);
}

function run(cmd, args, opts = {}) {
  const res = spawnSync(cmd, args, { stdio: "pipe", encoding: "utf8", ...opts });
  if (res.error) fail(`${cmd} could not be started: ${res.error.message}`);
  if (res.status !== 0) {
    process.stdout.write(res.stdout ?? "");
    process.stderr.write(res.stderr ?? "");
    fail(`${cmd} ${args.join(" ")} exited with ${res.status}`);
  }
  return res.stdout;
}

async function readJson(file) {
  return JSON.parse(await readFile(file, "utf8"));
}

// ---------------------------------------------------------------------------------------------
// 1. Schema sanity (Ajv strict) — fails fast before generating anything
// ---------------------------------------------------------------------------------------------
function makeAjv() {
  const ajv = new Ajv2020({ strict: true, allErrors: true, discriminator: true, allowUnionTypes: true });
  // json-schema-to-typescript annotation keyword (no validation semantics)
  ajv.addKeyword({ keyword: "tsType", schemaType: "string" });
  return ajv;
}

async function loadSchemas() {
  const out = {};
  for (const c of CONTRACTS) out[c.module] = await readJson(path.join(SCHEMA_DIR, c.schema));
  return out;
}

// ---------------------------------------------------------------------------------------------
// 2. TypeScript
// ---------------------------------------------------------------------------------------------
async function generateTs(schemas, outDir) {
  await mkdir(outDir, { recursive: true });
  const exportsByName = new Map(); // name -> module (first wins; duplicates must be identical)
  const declarations = new Map(); // name -> declaration text (for duplicate check)

  for (const c of CONTRACTS) {
    const ts = await compile(structuredClone(schemas[c.module]), c.root, {
      bannerComment: TS_BANNER,
      cwd: SCHEMA_DIR,
      additionalProperties: false,
      unreachableDefinitions: c.allDefinitions === true,
      strictIndexSignatures: true,
      format: true,
      style: { printWidth: 100, singleQuote: false, semi: true, trailingComma: "all" },
    });
    await writeFile(path.join(outDir, `${c.module}.ts`), ts);

    const re = /^export (?:interface|type) (\w+)[\s\S]*?(?=^export |(?![\s\S]))/gm;
    for (const m of ts.matchAll(re)) {
      const name = m[1];
      const decl = m[0].replace(/\/\*\*[\s\S]*?\*\//g, "").trim();
      if (!exportsByName.has(name)) {
        exportsByName.set(name, c.module);
        declarations.set(name, decl);
      } else if (declarations.get(name) !== decl) {
        fail(`TS type "${name}" is declared differently in ${exportsByName.get(name)} and ${c.module}`);
      }
    }
  }

  const byModule = new Map();
  for (const [name, mod] of exportsByName) {
    if (!byModule.has(mod)) byModule.set(mod, []);
    byModule.get(mod).push(name);
  }
  const lines = [TS_BANNER, ""];
  for (const c of CONTRACTS) {
    const names = (byModule.get(c.module) ?? []).sort();
    lines.push(`export type {\n${names.map((n) => `  ${n},`).join("\n")}\n} from "./${c.module}";`);
  }
  lines.push("", `export const SCHEMA_VERSION = "${SCHEMA_VERSION}" as const;`, "");
  await writeFile(path.join(outDir, "index.ts"), lines.join("\n"));
}

// ---------------------------------------------------------------------------------------------
// 3. Python (Pydantic v2) via pinned datamodel-code-generator (uvx)
// ---------------------------------------------------------------------------------------------
async function generatePy(outPkgDir) {
  await mkdir(outPkgDir, { recursive: true });
  for (const c of CONTRACTS) {
    run("uvx", [
      "--from",
      `datamodel-code-generator==${DMCG_VERSION}`,
      "datamodel-codegen",
      "--input",
      path.join(SCHEMA_DIR, c.schema),
      "--input-file-type",
      "jsonschema",
      "--output",
      path.join(outPkgDir, `${c.module}.py`),
      "--output-model-type",
      "pydantic_v2.BaseModel",
      "--target-python-version",
      "3.11",
      "--class-name",
      c.root,
      "--use-annotated",
      "--field-constraints",
      "--collapse-root-models",
      // constrained array items (face ids >= 0) become TypeAliasType instead of RootModel wrappers,
      // fixed-length arrays (Vec3, lod0_tri_range, transform_4x4) become tuples like the TS side
      "--use-type-alias",
      "--use-tuple-for-fixed-length-arrays",
      "--use-standard-collections",
      "--use-union-operator",
      "--enum-field-as-literal",
      "all",
      "--use-double-quotes",
      "--use-schema-description",
      "--use-field-description",
      "--disable-timestamp",
      "--custom-file-header",
      PY_HEADER,
    ]);
  }

  // Ship the schemas inside the Python package as well (runtime jsonschema validation).
  const pySchemaDir = path.join(outPkgDir, "schemas");
  await mkdir(pySchemaDir, { recursive: true });
  for (const c of CONTRACTS) await cp(path.join(SCHEMA_DIR, c.schema), path.join(pySchemaDir, c.schema));

  const init = `${PY_HEADER}
"""RevGate SSOT data contracts (Pydantic v2), generated from packages/contracts/schemas."""

from __future__ import annotations

import json
from functools import cache
from importlib import resources
from typing import Any

from .analytical_meta import AnalyticalMeta
from .diff_manifest import DiffManifest
from .manufacturing import ApprovalSnapshot, AttachmentItem, MissingSpecWarning, SpecCardV2, SpecDiffItem

SCHEMA_VERSION = "${SCHEMA_VERSION}"

__all__ = [
    "SCHEMA_VERSION", "AnalyticalMeta", "ApprovalSnapshot", "AttachmentItem", "DiffManifest", "MissingSpecWarning",
    "SpecCardV2", "SpecDiffItem", "load_schema",
]


@cache
def load_schema(name: str) -> dict[str, Any]:
    """Return the JSON Schema dict for \`analytical_meta\`, \`diff_manifest\` or \`manufacturing\`."""
    if name not in ("analytical_meta", "diff_manifest", "manufacturing"):
        raise KeyError(name)
    text = resources.files(__package__).joinpath("schemas", f"{name}.schema.json").read_text("utf-8")
    return json.loads(text)
`;
  await writeFile(path.join(outPkgDir, "__init__.py"), init);
  await writeFile(path.join(outPkgDir, "py.typed"), "");
}

// ---------------------------------------------------------------------------------------------
// Verification
// ---------------------------------------------------------------------------------------------
async function loadCases() {
  const cases = {};
  for (const c of CONTRACTS) {
    const good = await readJson(path.join(EXAMPLE_DIR, `${c.module}.example.json`));
    const badFile = path.join(EXAMPLE_DIR, `${c.module}.invalid.json`);
    const bad = existsSync(badFile) ? await readJson(badFile) : [];
    cases[c.module] = { good, bad };
  }
  return cases;
}

function verifyAjv(schemas, cases) {
  const ajv = makeAjv();
  for (const c of CONTRACTS) {
    const validate = ajv.compile(schemas[c.module]);
    if (!validate(cases[c.module].good)) {
      fail(`ajv rejected examples/${c.module}.example.json: ${ajv.errorsText(validate.errors)}`);
    }
    for (const bad of cases[c.module].bad) {
      if (validate(bad.document)) fail(`ajv accepted invalid case "${bad.name}" for ${c.module}`);
    }
    log(`ajv ✓ ${c.module}: example valid, ${cases[c.module].bad.length} invalid cases rejected`);
  }
}

async function verifyTs(tsDir, cases) {
  const tmp = await mkdtemp(path.join(os.tmpdir(), "revgate-contracts-ts-"));
  try {
    await cp(tsDir, path.join(tmp, "ts"), { recursive: true });
    const body = [
      `import type { AnalyticalMeta, ApprovalSnapshot, AttachmentItem, DiffManifest, FaceParams, MissingSpecWarning, SpecCardV2, SpecDiffItem, Vec3 } from "./ts/index";`,
      `import { SCHEMA_VERSION } from "./ts/index";`,
      `export const meta = ${JSON.stringify(cases.analytical_meta.good, null, 2)} satisfies AnalyticalMeta;`,
      `export const manifest = ${JSON.stringify(cases.diff_manifest.good, null, 2)} satisfies DiffManifest;`,
      `export const snapshot = ${JSON.stringify(cases.manufacturing.good, null, 2)} satisfies ApprovalSnapshot;`,
      // Phase 4 shared read models must be exported and usable on their own
      `export const card: SpecCardV2 = snapshot.target_rev.spec_card;`,
      `export const diffs: SpecDiffItem[] = snapshot.spec_diffs;`,
      `export const warn: MissingSpecWarning = { code: "MISSING_TOLERANCE", level: "ACK_REQUIRED", message: "x" };`,
      `export const att: AttachmentItem = { id: "a", revision_id: "r", kind: "2D_DXF", filename: "f.dxf", content_type: "application/dxf", file_size_bytes: 1, file_sha256: "${"0".repeat(64)}", status: "READY", created_at: "2026-11-24T00:00:00Z", url: null };`,
      // discriminated-union narrowing must work on the generated types
      `export function radiusOf(p: FaceParams): number { return p.type === "CYLINDER" ? p.radius_mm : 0; }`,
      `export const v: Vec3 = [0, 0, 1];`,
      `export const version: "1.0.0" = SCHEMA_VERSION;`,
      `export const t: number[] = manifest.alignment.transform_4x4;`,
      "",
    ].join("\n");
    await writeFile(path.join(tmp, "verify.ts"), body);
    const tsc = require.resolve("typescript/bin/tsc");
    run(process.execPath, [
      tsc,
      "--noEmit",
      "--strict",
      "--exactOptionalPropertyTypes",
      "--noUncheckedIndexedAccess",
      "--target",
      "ES2022",
      "--module",
      "ESNext",
      "--moduleResolution",
      "Bundler",
      "--skipLibCheck",
      path.join(tmp, "verify.ts"),
    ]);
    log("tsc ✓ generated TS types accept the examples (strict, exactOptionalPropertyTypes)");
  } finally {
    await rm(tmp, { recursive: true, force: true });
  }
}

function verifyPy() {
  const out = run("uv", [
    "run",
    "--project",
    PY_PROJECT,
    "--group",
    "dev",
    "python",
    path.join(PKG_ROOT, "scripts", "verify_py.py"),
    EXAMPLE_DIR,
  ], { env: { ...process.env, PYTHONUTF8: "1", PYTHONIOENCODING: "utf-8" } });
  process.stdout.write(out);
}

// ---------------------------------------------------------------------------------------------
async function listFiles(dir, base = dir) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const ent of await readdir(dir, { withFileTypes: true })) {
    if (ent.name === "__pycache__") continue;
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) out.push(...(await listFiles(p, base)));
    else out.push(path.relative(base, p).split(path.sep).join("/"));
  }
  return out.sort();
}

async function assertNoDrift(generatedDir, committedDir, label) {
  const a = await listFiles(generatedDir);
  const b = await listFiles(committedDir);
  if (JSON.stringify(a) !== JSON.stringify(b)) fail(`${label}: file set drift (${b} vs ${a})`);
  for (const f of a) {
    const x = await readFile(path.join(generatedDir, f), "utf8");
    const y = await readFile(path.join(committedDir, f), "utf8");
    if (x.replace(/\r\n/g, "\n") !== y.replace(/\r\n/g, "\n")) fail(`${label}: ${f} is stale — run pnpm codegen`);
  }
  log(`${label} ✓ committed output matches the schemas`);
}

async function main() {
  const schemas = await loadSchemas();
  const cases = await loadCases();
  verifyAjv(schemas, cases);

  const tsDir = path.join(PKG_ROOT, "ts");
  const pyPkgDir = path.join(PY_PROJECT, "revgate_contracts");

  if (checkMode) {
    const tmp = await mkdtemp(path.join(os.tmpdir(), "revgate-contracts-"));
    try {
      await generateTs(schemas, path.join(tmp, "ts"));
      await generatePy(path.join(tmp, "py"));
      await assertNoDrift(path.join(tmp, "ts"), tsDir, "ts");
      await assertNoDrift(path.join(tmp, "py"), pyPkgDir, "py");
    } finally {
      await rm(tmp, { recursive: true, force: true });
    }
  } else {
    await rm(tsDir, { recursive: true, force: true });
    await generateTs(schemas, tsDir);
    log(`ts ✓ wrote ${(await listFiles(tsDir)).map((f) => `ts/${f}`).join(", ")}`);
    for (const c of CONTRACTS) await rm(path.join(pyPkgDir, `${c.module}.py`), { force: true });
    await generatePy(pyPkgDir);
    log(`py ✓ wrote ${(await listFiles(pyPkgDir)).map((f) => `py/revgate_contracts/${f}`).join(", ")}`);
  }

  await verifyTs(tsDir, cases);
  verifyPy();
  log("done");
}

main().catch((err) => fail(err?.stack ?? String(err)));
