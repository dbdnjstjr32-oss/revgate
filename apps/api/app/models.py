"""ORM mapping of the 11 tables of IMPLEMENTATION_BLUEPRINT §3 + the Phase 4 extension
(docs/PHASE4_MANUFACTURING_SPEC.md §1: revision spec versioning, approval snapshot / supersede columns,
12th table revision_attachments).

The DDL itself is applied verbatim by migrations/versions/0001_initial_schema.py and
0002_phase4_manufacturing_trust.py; this module only mirrors it for querying (tests/test_schema.py
checks the two never drift).
PK policy: UUIDv7 generated by the application (app.ids.uuid7), audit_events uses BIGSERIAL.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import BigInteger, Boolean, ForeignKey, Integer, Text, text
from sqlalchemy.dialects.postgresql import ARRAY, DOUBLE_PRECISION, JSONB, TIMESTAMP, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from .ids import uuid7

TS = TIMESTAMP(timezone=True)
NOW = text("now()")


class Base(DeclarativeBase):
    __mapper_args__ = {"eager_defaults": True}


def _pk() -> Mapped[uuid.UUID]:
    return mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid7)


class Workspace(Base):
    __tablename__ = "workspaces"
    id: Mapped[uuid.UUID] = _pk()
    name: Mapped[str] = mapped_column(Text, nullable=False)
    plan: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("'FREE'"))
    security_mode: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("'TTL_VAULT'"))
    retention_days: Mapped[int] = mapped_column(Integer, nullable=False, server_default=text("30"))
    created_at: Mapped[datetime] = mapped_column(TS, nullable=False, server_default=NOW)


class User(Base):
    __tablename__ = "users"
    id: Mapped[uuid.UUID] = _pk()
    workspace_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("workspaces.id", ondelete="CASCADE"), nullable=False)
    email: Mapped[str] = mapped_column(Text, nullable=False, unique=True)
    name: Mapped[str] = mapped_column(Text, nullable=False)
    role: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("'ENGINEER'"))
    created_at: Mapped[datetime] = mapped_column(TS, nullable=False, server_default=NOW)


class ShopInbox(Base):
    __tablename__ = "shop_inboxes"
